// Generate docs/COMMANDS.md — the page /help links to.
//
// The page is written, not maintained: every command, its section and its
// sentence come from the same table and the same translations the chat uses, so
// the link in /help cannot point at a list that drifted. All three languages sit
// on one page behind a language bar, because the repository has one page and the
// person reading it may speak any of them.
//
//   node scripts/commands-doc.mjs
//
// `test/commands-doc.test.mjs` fails when the committed file stops matching.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { COMMAND_ALIASES } from '../chat/commands-registry.mjs';
import { HELP_SECTIONS } from '../chat/help-sections.mjs';
import { t } from '../core/i18n.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'docs', 'COMMANDS.md');

/** The languages, in the order the repository already speaks them. */
export const DOC_LANGS = ['en', 'ru', 'zh'];

/** The heading of each language block; the language bar links to it. */
export const LANG_HEAD = { en: 'English', ru: 'Русский', zh: '中文' };

const NOTE = {
  en: 'Built from the same code as `/help`: the list, the sections and the sentences are the bot’s own. `/help` answers in the language of the chat; this page holds all three.',
  ru: 'Собрано из того же кода, что и `/help`: список, разделы и пояснения совпадают с ботом. В чате `/help` отвечает на языке темы, а на этой странице — все три языка.',
  zh: '本页与 `/help` 用同一份代码生成：列表、分组和说明与机器人完全一致。/help 用话题的语言回答，这里三种语言都在。',
};

/** One line per command: `/name` and the sentence /help gives when asked. */
function sectionLines(lang, section) {
  const lines = [`### ${t(lang, `help.section.${section.id}`)}`, ''];
  for (const command of section.commands) {
    let about = String(t(lang, `ctrl.help.about.${command}`)).replace(/\s+/g, ' ').trim();
    // Some sentences open by naming the command again; the bullet already does.
    about = about.replace(new RegExp(`^/${command}\\s*[—-]?\\s*`, 'i'), '').trim();
    lines.push(`- \`/${command}\` — ${about}`);
  }
  return lines.join('\n');
}

/** The old spellings that still work, so "all commands" means all of them. */
function aliasLines(lang) {
  const pairs = Object.entries(COMMAND_ALIASES).map(([alias, owner]) => `\`/${alias}\` → \`/${owner}\``);
  return [`### ${t(lang, 'help.aliases.title')}`, '', t(lang, 'help.aliases.note'), '', pairs.join(' · ')].join('\n');
}

/** The whole page. Exported so the drift test can diff it without writing. */
export function commandsDoc() {
  const bar = DOC_LANGS.map((lang) => `[${LANG_HEAD[lang]}](#${LANG_HEAD[lang].toLowerCase()})`).join(' · ');
  const parts = [
    '# Commands — DSH Telegram bridge',
    '',
    '> Generated by `node scripts/commands-doc.mjs` from `chat/help-sections.mjs` and the',
    '> `ctrl.help.about.*` translations. Edit those, not this file.',
    '',
    bar,
  ];
  for (const lang of DOC_LANGS) {
    parts.push('', `## ${LANG_HEAD[lang]}`, '', NOTE[lang], '');
    for (const section of HELP_SECTIONS) parts.push(sectionLines(lang, section), '');
    parts.push(aliasLines(lang), '');
  }
  return `${parts.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`;
}

if (process.argv[1] && process.argv[1].endsWith('commands-doc.mjs')) {
  writeFileSync(OUT, commandsDoc(), 'utf8');
  console.log(`wrote ${OUT}`);
}
