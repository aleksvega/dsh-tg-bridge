// install-hooks.mjs — make the secret scan impossible to forget.
//
// A check that has to be remembered is not a check: `jev-gate` was run by hand,
// and the push that carried a machine id simply did not run it. So the scanner
// is wired into git itself, once per clone:
//
//   pre-commit  refuses a commit whose staged lines carry a secret
//   pre-push    refuses the push, and repeats the scan for `--no-verify` commits
//
// `core.hooksPath` points at `.githooks`, which is committed here, so the hook
// follows the repo instead of living in a git directory git does not track.
//
// Usage: node install-hooks.mjs [--uninstall]
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, chmodSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const HOOKS_DIR = '.githooks';

const SCAN = `#!/bin/sh
# Generated by install-hooks.mjs — the secret scan must run, not be remembered.
here=$(git rev-parse --show-toplevel) || exit 0
node "$here/scan-secrets.mjs" || exit 1
`;

const PRE_PUSH = `#!/bin/sh
# Generated by install-hooks.mjs — the secret scan must run, not be remembered.
here=$(git rev-parse --show-toplevel) || exit 0
# A commit made with --no-verify skipped pre-commit, so the push checks it too.
range=$(git rev-list --reverse --not --remotes HEAD 2>/dev/null | head -n 1)
if [ -n "$range" ]; then
  base=$(git rev-parse "$range" 2>/dev/null)
  node "$here/scan-secrets.mjs" --range "$base..HEAD" || exit 1
fi
# The whole history is checked as advice, not as a gate: an identity that is
# already on the remote cannot be fixed by refusing this push, and a hook that
# blocks every future push over an old commit is one people learn to bypass
# with --no-verify — which would let the next real finding through too. The
# identity is reported loudly and the push proceeds; the fix is a rewrite.
node "$here/scan-secrets.mjs" --all --report-only
`;

function git(...args) {
  return execFileSync('git', args, { encoding: 'utf8' }).trim();
}

if (!existsSync('.git') && !git('rev-parse', '--git-dir')) {
  console.error('not a git repository');
  process.exit(1);
}

if (process.argv.includes('--uninstall')) {
  try {
    git('config', '--unset', 'core.hooksPath');
  } catch {
    // already unset
  }
  console.log('hooks uninstalled (core.hooksPath cleared)');
  process.exit(0);
}

mkdirSync(HOOKS_DIR, { recursive: true });
for (const [name, body] of [['pre-commit', SCAN], ['pre-push', PRE_PUSH]]) {
  const path = join(HOOKS_DIR, name);
  writeFileSync(path, body, { encoding: 'utf8', mode: 0o755 });
  try {
    chmodSync(path, 0o755);
  } catch {
    // Windows has no exec bit; git runs the hook regardless.
  }
}
git('config', 'core.hooksPath', HOOKS_DIR);
console.log(`hooks installed: core.hooksPath = ${HOOKS_DIR} (${git('rev-parse', '--show-toplevel')})`);